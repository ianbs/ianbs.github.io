const LANGUAGE_STORAGE_KEY = "site-language";

const resolveLanguage = (value) => {
	return value === "en" ? "en" : "pt";
};

const applyLanguage = (language) => {
	const selectedLanguage = resolveLanguage(language);
	const copy = TRANSLATIONS[selectedLanguage];

	document.documentElement.lang = selectedLanguage === "en" ? "en" : "pt-BR";
	document.title = copy.pageTitle;

	const metaDescription = document.querySelector('meta[name="description"]');
	if (metaDescription) {
		metaDescription.setAttribute("content", copy.metaDescription);
	}

	document.querySelectorAll("[data-i18n]").forEach((element) => {
		const key = element.getAttribute("data-i18n");
		if (!key || !copy[key]) {
			return;
		}
		element.textContent = copy[key];
	});

	const languageToggle = document.getElementById("language-toggle");
	if (languageToggle) {
		languageToggle.textContent = copy.languageToggleText;
		languageToggle.setAttribute("aria-label", copy.languageToggleAria);
	}

	localStorage.setItem(LANGUAGE_STORAGE_KEY, selectedLanguage);
	document.dispatchEvent(
		new CustomEvent("siteLanguageChange", {
			detail: { language: selectedLanguage },
		})
	);

	return selectedLanguage;
};

document.addEventListener("DOMContentLoaded", () => {
	const yearElement = document.getElementById("current-year");
	if (yearElement) {
		yearElement.textContent = String(new Date().getFullYear());
	}

	let currentLanguage = applyLanguage(localStorage.getItem(LANGUAGE_STORAGE_KEY));

	const languageToggle = document.getElementById("language-toggle");
	if (languageToggle) {
		languageToggle.addEventListener("click", () => {
			const nextLanguage = currentLanguage === "pt" ? "en" : "pt";
			currentLanguage = applyLanguage(nextLanguage);
		});
	}

	const sections = document.querySelectorAll(".section-observe");
	if (!sections.length) {
		return;
	}

	const observer = new IntersectionObserver(
		(entries, localObserver) => {
			entries.forEach((entry) => {
				if (entry.isIntersecting) {
					entry.target.classList.add("is-visible");
					localObserver.unobserve(entry.target);
				}
			});
		},
		{
			threshold: 0.16,
			rootMargin: "0px 0px -8% 0px",
		}
	);

	sections.forEach((section, index) => {
		section.style.transitionDelay = `${index * 0.08}s`;
		observer.observe(section);
	});
});
